CREATE OR REPLACE FUNCTION pg_temp.corrigir_texto(txt text)
RETURNS text AS $fn$
DECLARE
  m record;
  r text := txt;
BEGIN
  IF txt IS NULL THEN RETURN NULL; END IF;
  FOR m IN SELECT corrompido, correto FROM pg_temp.mapa_correcao LOOP
    IF position(m.corrompido in r) > 0 THEN
      r := replace(r, m.corrompido, m.correto);
    END IF;
  END LOOP;
  RETURN r;
END;
$fn$ LANGUAGE plpgsql;

UPDATE gbp_eleitores SET
  nome        = pg_temp.corrigir_texto(nome),
  logradouro  = pg_temp.corrigir_texto(logradouro),
  cidade      = pg_temp.corrigir_texto(cidade),
  bairro      = pg_temp.corrigir_texto(bairro),
  complemento = pg_temp.corrigir_texto(complemento),
  nome_mae    = pg_temp.corrigir_texto(nome_mae),
  genero      = pg_temp.corrigir_texto(genero),
  instagram   = pg_temp.corrigir_texto(instagram)
