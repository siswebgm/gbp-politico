   OR logradouro  LIKE '%' || chr(65533) || '%'
   OR cidade      LIKE '%' || chr(65533) || '%'
   OR bairro      LIKE '%' || chr(65533) || '%'
   OR complemento LIKE '%' || chr(65533) || '%'
   OR nome_mae    LIKE '%' || chr(65533) || '%'
   OR genero      LIKE '%' || chr(65533) || '%'
